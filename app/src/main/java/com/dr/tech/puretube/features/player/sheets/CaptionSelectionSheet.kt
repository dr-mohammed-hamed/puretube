/**
 * Caption selection sheet: CC toggle plus language list from the
 * extracted subtitles (label + auto-generated badge) and an off option.
 * PureTheme tokens only, RTL by default.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun CaptionSelectionSheet(
    ccEnabled: Boolean,
    selectedLang: String?,
    tracks: List<SubtitleTrack>,
    onCcToggle: (Boolean) -> Unit,
    onLanguageSelected: (String?) -> Unit,
    onDismiss: () -> Unit
) {
    val sheetState = rememberModalBottomSheetState(skipPartiallyExpanded = true)

    ModalBottomSheet(
        onDismissRequest = onDismiss,
        sheetState = sheetState,
        containerColor = PureTheme.colors.surface
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .padding(horizontal = 24.dp, vertical = 16.dp)
        ) {
            Text(
                text = "الترجمة",
                style = PureTheme.typography.headlineMedium,
                color = PureTheme.colors.textPrimary
            )

            Spacer(modifier = Modifier.height(8.dp))

            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .clickable { onCcToggle(!ccEnabled) }
                    .padding(vertical = 12.dp),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = "تفعيل الترجمة",
                    style = PureTheme.typography.bodyMedium,
                    color = PureTheme.colors.textPrimary
                )
                Switch(
                    checked = ccEnabled,
                    onCheckedChange = onCcToggle,
                    colors = SwitchDefaults.colors(
                        checkedThumbColor = PureTheme.colors.background,
                        checkedTrackColor = PureTheme.colors.primary,
                        uncheckedThumbColor = PureTheme.colors.textSecondary,
                        uncheckedTrackColor = PureTheme.colors.surfaceElevated,
                        uncheckedBorderColor = PureTheme.colors.borderOutline
                    )
                )
            }

            HorizontalDivider(color = PureTheme.colors.borderOutline)

            CaptionOptionRow(
                label = "إيقاف الترجمة",
                selected = !ccEnabled || selectedLang == null,
                onClick = {
                    onLanguageSelected(null)
                    onDismiss()
                }
            )

            if (tracks.isEmpty()) {
                Text(
                    text = "لا توجد ترجمات متاحة لهذا المقطع",
                    style = PureTheme.typography.bodyMedium,
                    color = PureTheme.colors.textSecondary,
                    modifier = Modifier.padding(vertical = 12.dp)
                )
            } else {
                tracks.forEach { track ->
                    val displayLabel = buildString {
                        append(track.label.ifBlank { track.languageCode })
                        if (track.isAutoGenerated) append(" (تلقائية)")
                    }
                    CaptionOptionRow(
                        label = displayLabel,
                        selected = ccEnabled && track.languageCode.equals(selectedLang, ignoreCase = true),
                        onClick = {
                            onLanguageSelected(track.languageCode)
                            onDismiss()
                        }
                    )
                }
            }

            Spacer(modifier = Modifier.height(24.dp))
        }
    }
}

@Composable
private fun CaptionOptionRow(
    label: String,
    selected: Boolean,
    onClick: () -> Unit
) {
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .clickable(onClick = onClick)
            .padding(vertical = 12.dp),
        horizontalArrangement = Arrangement.SpaceBetween,
        verticalAlignment = Alignment.CenterVertically
    ) {
        Text(
            text = label,
            style = PureTheme.typography.bodyMedium,
            color = if (selected) PureTheme.colors.primary else PureTheme.colors.textPrimary,
            maxLines = 1,
            overflow = TextOverflow.Ellipsis,
            modifier = Modifier.weight(1f)
        )
        if (selected) {
            Icon(
                imageVector = Icons.Default.Check,
                contentDescription = null,
                tint = PureTheme.colors.primary,
                modifier = Modifier.size(20.dp)
            )
        }
    }
}
