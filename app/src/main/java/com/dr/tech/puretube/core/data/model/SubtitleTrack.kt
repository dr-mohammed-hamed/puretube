package com.dr.tech.puretube.core.data.model

/**
 * مسار ترجمة مستخرج من StreamInfo (روابط مؤقتة في الذاكرة فقط — المبدأ VIII).
 */
data class SubtitleTrack(
    val url: String,
    val mimeType: String,
    val languageCode: String,
    val label: String,
    val isAutoGenerated: Boolean = false
) {
    val isArabic: Boolean
        get() = languageCode.lowercase().startsWith("ar")

    val isEnglish: Boolean
        get() = languageCode.lowercase().startsWith("en")
}
